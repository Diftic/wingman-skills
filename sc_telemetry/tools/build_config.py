"""Write default_config.yaml from the event catalogue, so the switches can never drift from the code.

Run after changing sc_telemetry_core/events.py or the tracked-states list below:
    python tools/build_config.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SKILL_DIR / "dependencies"))

from sc_telemetry_core.events import EVENTS, GROUP_PREFIX, GROUPS

VERSION = "0.1.0"
TRACKED = ("speed, heading, altitude, radar altitude, vertical speed, g-force, fuel, boost, landing gear, flight modes, "
           "power, warning lights, weapons and countermeasures; health, hunger, thirst, oxygen, heart rate, "
           "surroundings and the UEC balance")
"""Read all the time and answered through the tools."""


def _hint() -> str:
    """Only two settings are shown (user, 2026-10-29): every reaction is on, so the hint says what they are."""
    groups = []
    for group in GROUPS:
        names = sorted(spec.name.lower() + ("*" if not spec.tested else "") for spec in EVENTS if spec.group == group)
        groups.append(f"<li><strong>{GROUP_PREFIX[group]}:</strong> {', '.join(names)}</li>")
    return (
        "<p><strong>Needs Star Citizen telemetry switched on:</strong> turn on \"Enable Star Citizen telemetry\" "
        "above, then quit the RSI Launcher completely (tray too) and start it again.</p>"
        "<p><strong>Your Wingman reacts to</strong> (all on; \"Enable Proactive Notifications\" mutes them all; "
        f"* = not yet confirmed in a live test):</p><ul>{''.join(groups)}</ul>"
        f"<p><strong>Always tracked</strong> (for questions to your Wingman): {TRACKED}. "
        "Position is not part of the game's telemetry.</p>"
    )


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _boolean(key: str, name: str, value: bool, hint: str | None = None) -> list[str]:
    lines = [f"  - id: {key}", f"    name: {_quote(name)}"]
    if hint:
        lines.append(f"    hint: {_quote(hint)}")
    return lines + ["    property_type: boolean", "    required: false", f"    value: {str(value).lower()}"]


def build() -> str:
    out = [
        "# Generated by tools/build_config.py from sc_telemetry_core/events.py. Do not edit by hand.",
        "module: skills.sc_telemetry.main",
        "api_version: 3",
        "name: SC_Telemetry",
        "display_name: Star Citizen Telemetry",
        "author: Mallachi",
        f"version: {VERSION}",
        "platforms: [windows]",
        "auto_activate: true",
        "tags:",
        "  - Star Citizen",
        "  - Game Integration",
        "description:",
        "  en: Live ship and pilot status from Star Citizen's own telemetry. Your Wingman reacts and answers.",
        f"hint:\n  en: {_quote(_hint())}",
        "discovery_keywords:",
        *[f"  - {word}" for word in ("ship status", "shields", "speed", "altitude", "heading", "power",
                                     "warning lights", "countermeasures", "health", "hunger", "thirst",
                                     "oxygen", "telemetry")],
        "prompt: |",
        "  Use get_ship_status for questions about the ship the player sits in (speed, altitude, heading, power,",
        "  shields, warnings, weapons, countermeasures) and get_player_status for the pilot (health, hunger, thirst,",
        "  oxygen, surroundings, wallet). Report the values the tools give; never estimate them. There is no",
        "  position in this data: for where the player is, use the game-log tools.",
        "custom_properties:",
        *_boolean("enable_telemetry", "Enable Star Citizen telemetry", False,
                  "Sets the Windows user variable GRPC_CLIENT_SERVER_ENABLED=true that switches on the game's own "
                  "local telemetry (read-only, on this PC only). Takes effect after you quit the RSI Launcher "
                  "completely (tray too) and start it again. Turning this off removes the variable."),
        *_boolean("proactive_notifications", "Enable Proactive Notifications", True,
                  "Lets your Wingman react to what happens to the ship and the pilot. Off: it stays quiet and only "
                  "answers questions."),
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    (SKILL_DIR / "default_config.yaml").write_text(build(), encoding="utf-8")
    print("default_config.yaml written")
